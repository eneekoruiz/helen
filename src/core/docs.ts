import path from "node:path";
import { getAllModules } from "../modules/registry.js";
import { logger } from "./logger.js";
import { ensureDir, isSafeProjectPath } from "./fs.js";
import { runProjectOperation, writeAtomicFile } from "./operations.js";

/**
 * Generate markdown documentation for all registered modules.
 */
export async function generateModuleDocs(cwd: string): Promise<void> {
  await runProjectOperation(cwd, "generate-docs", async () => {
    const docsDir = path.join(cwd, "docs", "modules");
    if (!isSafeProjectPath(cwd, docsDir))
      throw new Error("Documentation must remain inside the project directory");
    ensureDir(docsDir);

    const modules = getAllModules();

    for (const mod of modules) {
      const { meta } = mod;
      const filePath = path.join(docsDir, `${meta.id}.md`);

      const content = `# ${meta.name} (${meta.id})

${meta.summary}

## Category
${meta.category}

## Description
${meta.description}

## Problem it Solves
${meta.problemItSolves}

## Usage Information
- **Risk Level**: ${meta.riskLevel}
- **Recommended Skill Level**: ${meta.recommendedLevel}

### When to Use
${meta.whenToUse}

### When NOT to Use
${meta.whenNotToUse}

## Technical Details

### Files Created
${meta.filesCreated.map((f) => `- ` + f).join("\n")}

### Files Modified
${meta.filesModified.map((f) => `- ` + f).join("\n")}

### Dependencies
- **Runtime**: ${meta.runtimeDependencies.length > 0 ? meta.runtimeDependencies.join(", ") : "None"}
- **Dev**: ${meta.devDependencies.length > 0 ? meta.devDependencies.join(", ") : "None"}

### Requirements
${meta.requirements.map((r) => `- ` + r).join("\n")}

## Risks & Warnings
${meta.risks.map((r) => `- ` + r).join("\n")}

## Post-Installation Steps
${meta.nextSteps.map((s) => `- ` + s).join("\n")}
`;

      writeAtomicFile(filePath, content);
      logger.step(`Generated docs: ${filePath}`);
    }

    // Generate README.md index
    const indexContent = `# HELEN Module Documentation

Integrated documentation for all HELEN modules.

| Module | Category | Description |
|--------|----------|-------------|
${modules.map((m) => `| [${m.meta.name}](${m.meta.id}.md) | ${m.meta.category} | ${m.meta.summary} |`).join("\n")}

---
Generated by HELEN CLI
`;

    writeAtomicFile(path.join(docsDir, "README.md"), indexContent);
    logger.success("Documentation generated successfully.");
  });
}
